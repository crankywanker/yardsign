// Builds the pixel into one minified file and a tiny module the Worker imports.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MAX_BYTES = 4 * 1024;

/** Placeholder host for the install snippet. Build-time constant; change it here. */
const PIXEL_DEFAULT_HOST = process.env.PIXEL_HOST || 'https://cdn.tryyardsign.com';

const result = await build({
  entryPoints: [join(here, 'src/pixel.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2017'],
  write: false,
  legalComments: 'none',
});
const code = result.outputFiles[0].text.trim();
const bytes = Buffer.byteLength(code, 'utf8');
if (bytes > MAX_BYTES) {
  console.error(`pixel is ${bytes} bytes; limit is ${MAX_BYTES}`);
  process.exit(1);
}
for (const token of ['__YS_SITE_KEY__', '__YS_ENDPOINT__', '__YS_DELIVR__']) {
  if (!code.includes(token)) {
    console.error(`pixel is missing the ${token} token`);
    process.exit(1);
  }
}
const hash = createHash('sha256').update(code).digest('hex').slice(0, 12);

const dist = join(here, 'dist');
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'yardsign.js'), code + '\n');
writeFileSync(
  join(dist, 'index.js'),
  `// Generated by build.mjs. Do not edit.
export const PIXEL_SOURCE = ${JSON.stringify(code)};
export const PIXEL_SIZE_BYTES = ${bytes};
export const PIXEL_BUILD_HASH = ${JSON.stringify(hash)};
export const PIXEL_DEFAULT_HOST = ${JSON.stringify(PIXEL_DEFAULT_HOST)};
export const SITE_KEY_TOKEN = '__YS_SITE_KEY__';
export const ENDPOINT_TOKEN = '__YS_ENDPOINT__';
export const DELIVR_TOKEN = '__YS_DELIVR__';
const SAFE_KEY = /^[A-Za-z0-9_-]{4,64}$/;
const SAFE_PIXEL = /^[A-Za-z0-9-]{0,64}$/;
export function renderPixel(siteKey, collectUrl, delivrPixelId = '') {
  if (!SAFE_KEY.test(siteKey)) throw new Error('unsafe site key');
  if (!/^https?:\\/\\/[^'"\\\\\\s]+$/.test(collectUrl)) throw new Error('unsafe collect url');
  if (!SAFE_PIXEL.test(delivrPixelId || '')) throw new Error('unsafe partner pixel id');
  return PIXEL_SOURCE.split(SITE_KEY_TOKEN).join(siteKey).split(ENDPOINT_TOKEN).join(collectUrl).split(DELIVR_TOKEN).join(delivrPixelId || '');
}
export function installSnippet(siteKey, host = PIXEL_DEFAULT_HOST) {
  return '<script async src="' + host + '/p/' + siteKey + '.js"></script>';
}
`,
);
writeFileSync(
  join(dist, 'index.d.ts'),
  `export declare const PIXEL_SOURCE: string;
export declare const PIXEL_SIZE_BYTES: number;
export declare const PIXEL_BUILD_HASH: string;
export declare const PIXEL_DEFAULT_HOST: string;
export declare const SITE_KEY_TOKEN: string;
export declare const ENDPOINT_TOKEN: string;
export declare const DELIVR_TOKEN: string;
/** Bake a site key, collect URL and (optional) Delivr pixel id into the pixel source. Throws on unsafe input. */
export declare function renderPixel(siteKey: string, collectUrl: string, delivrPixelId?: string): string;
/** The one-line tag a contractor pastes into their site. */
export declare function installSnippet(siteKey: string, host?: string): string;
`,
);
console.log(`pixel: ${bytes} bytes (limit ${MAX_BYTES}), hash ${hash}`);
